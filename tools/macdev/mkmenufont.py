#!/usr/bin/env python3
"""mkmenufont.py OUT.h   the boot menu's font (uefi/files/.../BootManagerLib/HackiosFont.h): ASCII 32..126, 1 bit a pixel, cells of 24 x 48 pixels, rendered from DejaVu Sans Mono Bold
(Bitstream Vera licence, free) with Pillow. Run in the UEFI builder container (apt: fonts-dejavu-core; pip: pillow). The UEFI's own text drawing (AsciiPrintXY) came out as garbage on
the phone's panel; the menu draws its own glyphs now."""
import sys
from PIL import Image, ImageDraw, ImageFont

W, H = 24, 48
font = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf', 40)
out = ['/* generated by tools/macdev/mkmenufont.py: DejaVu Sans Mono Bold, ASCII 32..126, %d x %d cells, one row of %d bytes a pixel row (bit 7 = left) */' % (W, H, (W + 7) // 8),
       '#define HACKIOS_FONT_W %d' % W, '#define HACKIOS_FONT_H %d' % H, 'STATIC CONST UINT8 mHackiosFont[95][%d] = {' % (H * ((W + 7) // 8))]
for c in range(32, 127):
    im = Image.new('L', (W, H), 0)
    d = ImageDraw.Draw(im)
    box = d.textbbox((0, 0), chr(c), font=font)
    d.text(((W - (box[2] - box[0])) // 2 - box[0], 2), chr(c), font=font, fill=255)
    rows = []
    for y in range(H):
        for xb in range(0, W, 8):
            v = 0
            for k in range(8):
                x = xb + k
                v = v << 1 | (1 if x < W and im.getpixel((x, y)) > 110 else 0)
            rows.append(v)
    out.append('  { ' + ', '.join('0x%02x' % b for b in rows) + ' },  /* %r */' % chr(c))
out.append('};')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
